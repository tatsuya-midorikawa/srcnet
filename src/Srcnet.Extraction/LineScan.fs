/// T1 行指向抽出。
///
/// 構文解析器に依存しない。未対応言語や構文誤りを含むファイルでも、この段階の結果だけは
/// 必ず得られる。これにより「対応していない言語のファイルがグラフから消える」ことを防ぐ
/// （docs/extraction.md 2、docs/decisions.md ADR-3 の代償 3）。
///
/// 走査は `ReadOnlySpan<byte>` に対して 1 回だけ行い、行ごとの文字列割り当てをしない。
/// 文字列を作るのは、実際に抽出した名前と綴りに限る。
module Srcnet.Extraction.LineScan

