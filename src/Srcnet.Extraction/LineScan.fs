open System.Buffers
open System.Collections.Generic
open System.Text
open System.Threading
open Srcnet.Core.Graph
open Srcnet.Text
open Srcnet.Extraction.Model

/// 根拠コメントの見出し。docs/graph-model.md 1 の `Note` に対応する。
let private noteTags = [| "TODO"; "FIXME"; "NOTE"; "HACK"; "SAFETY"; "XXX" |]

/// 生成コードのマーカー。大文字小文字を畳み込んでから比較する。
let private generatedMarkers =
  [| "do not edit"
     "do not modify"
     "autogenerated"
     "auto-generated"
     "automatically generated"
     "@generated"
     "generated by" |]

// --- バイト単位の述語 --------------------------------------------------------
// 識別子は「ASCII の英数字と `_`、および 0x80 以上のすべてのバイト」とする。
// 0x80 以上を一律に識別子の一部とみなすことで、UTF-8 の CJK 識別子が
// バイト境界で分断されない。復号は呼び出し側が済ませている前提である。

let inline private isIdentifierByte (b: byte) =
  (b >= 'a'B && b <= 'z'B)
  || (b >= 'A'B && b <= 'Z'B)
  || (b >= '0'B && b <= '9'B)
  || b = '_'B
  || b >= 0x80uy

let inline private isIdentifierStartByte (b: byte) =
  (b >= 'a'B && b <= 'z'B) || (b >= 'A'B && b <= 'Z'B) || b = '_'B || b >= 0x80uy

let inline private isBlank (b: byte) =
  b = ' 'B || b = '\t'B || b = '\r'B || b = 0x0Buy || b = 0x0Cuy

let private textOf (source: ReadOnlySpan<byte>) (start: int) (finish: int) =
  let from = max 0 start
  let until = min finish source.Length
  if until <= from then "" else Encoding.UTF8.GetString(source.Slice(from, until - from))

let private skipBlanks (line: ReadOnlySpan<byte>) (start: int) =
  let mutable index = max 0 start

  while index < line.Length && isBlank line[index] do
    index <- index + 1

  index

/// `start` から識別子を読み、終端位置を返す。識別子でなければ `start` を返す。
let private scanIdentifier (line: ReadOnlySpan<byte>) (start: int) =
  if start < 0 || start >= line.Length || not (isIdentifierStartByte line[start]) then max 0 start
  else
    let mutable index = start + 1

    while index < line.Length && isIdentifierByte line[index] do
      index <- index + 1

    index

/// 語が `start` に現れ、その直後が識別子の続きでないことを確かめる。
let private matchesWord (line: ReadOnlySpan<byte>) (start: int) (word: string) =
  if start < 0 || start + word.Length > line.Length then false
  else
    let mutable ok = true
    let mutable offset = 0

    while ok && offset < word.Length do
      if line[start + offset] <> byte word[offset] then ok <- false
      offset <- offset + 1

    ok && (start + word.Length >= line.Length || not (isIdentifierByte line[start + word.Length]))

let private matchesMarker (line: ReadOnlySpan<byte>) (start: int) (marker: string) =
  if start + marker.Length > line.Length then false
  else
    let mutable ok = true
    let mutable offset = 0

    while ok && offset < marker.Length do
      if line[start + offset] <> byte marker[offset] then ok <- false
      offset <- offset + 1

    ok

