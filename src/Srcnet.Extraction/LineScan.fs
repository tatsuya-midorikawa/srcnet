/// 定義候補の語彙規則。`Keyword` の直後に現れる識別子を定義名として拾う。
[<Struct>]
type private DefinitionRule = { Keyword: string; Kind: NodeKind }

let private rule keyword kind : DefinitionRule = { Keyword = keyword; Kind = kind }

let private cLikeRules =
  [| rule "struct" Type
     rule "union" Type
     rule "enum" Type
     rule "class" Type
     rule "namespace" Module
     rule "interface" Type |]

let private rustRules =
  [| rule "fn" Function
     rule "struct" Type
     rule "enum" Type
     rule "trait" Type
     rule "union" Type
     rule "type" Type
     rule "mod" Module
     rule "const" Constant
     rule "static" Variable |]

let private pythonRules = [| rule "def" Function; rule "class" Type |]

let private goRules = [| rule "func" Function; rule "type" Type |]

let private javaRules =
  [| rule "class" Type
     rule "interface" Type
     rule "enum" Type
     rule "record" Type |]

let private scriptRules =
  [| rule "function" Function
     rule "class" Type
     rule "interface" Type
     rule "enum" Type
     rule "type" Type |]

let private fsharpRules =
  [| rule "type" Type
     rule "module" Module
     rule "namespace" Module
     rule "val" Function |]

let private definitionRules language =
  match language with
  | Language.C
  | Language.CHeader
  | Language.Cpp
  | Language.CppHeader
  | Language.ObjectiveC
  | Language.ObjectiveCpp -> cLikeRules
  | Language.Rust -> rustRules
  | Language.Python -> pythonRules
  | Language.Go -> goRules
  | Language.Java
  | Language.CSharp -> javaRules
  | Language.JavaScript
  | Language.TypeScript
  | Language.Tsx -> scriptRules
  | Language.FSharp
  | Language.FSharpSignature -> fsharpRules
  | _ -> Array.empty

/// 取り込みの綴りの囲み方。
type private ImportStyle =
  /// `#include <x>` / `#include "x"`。
  | Preprocessor
  /// `import x.y.z;` のように識別子とドットで綴る。
  | Dotted
  /// `use a::b::c;`。
  | ScopedPath
  /// `import "x"` / `source "x"` のように引用符で囲む。
  | Quoted
  /// `include x` のように行の残りをそのまま綴りとする。
  | Bare

[<Struct>]
type private ImportRule =
  { Word: string
    Style: ImportStyle
    Edge: EdgeKind }

let private importRules language =
  match language with
  | Language.C
  | Language.CHeader
  | Language.Cpp
  | Language.CppHeader
  | Language.ObjectiveC
  | Language.ObjectiveCpp
  | Language.Assembly ->
    [| { Word = "include"; Style = Preprocessor; Edge = Includes }
       { Word = "include_next"; Style = Preprocessor; Edge = Includes }
       { Word = "import"; Style = Preprocessor; Edge = Includes } |]
  | Language.Python ->
    [| { Word = "from"; Style = Dotted; Edge = Imports }
       { Word = "import"; Style = Dotted; Edge = Imports } |]
  | Language.Rust ->
    [| { Word = "use"; Style = ScopedPath; Edge = Imports }
       { Word = "mod"; Style = ScopedPath; Edge = Imports } |]
  | Language.Java -> [| { Word = "import"; Style = Dotted; Edge = Imports } |]
  | Language.CSharp -> [| { Word = "using"; Style = Dotted; Edge = Imports } |]
  | Language.Go
  | Language.JavaScript
  | Language.TypeScript
  | Language.Tsx -> [| { Word = "import"; Style = Quoted; Edge = Imports } |]
  | Language.Shell -> [| { Word = "source"; Style = Bare; Edge = Imports } |]
  | Language.Makefile ->
    [| { Word = "include"; Style = Bare; Edge = Imports }
       { Word = "-include"; Style = Bare; Edge = Imports } |]
  | Language.Kconfig -> [| { Word = "source"; Style = Quoted; Edge = Imports } |]
  | Language.CMake -> [| { Word = "include"; Style = Quoted; Edge = Imports } |]
  | Language.FSharp
  | Language.FSharpSignature -> [| { Word = "open"; Style = Dotted; Edge = Imports } |]
  | _ -> Array.empty

/// 行コメントの開始記号。
